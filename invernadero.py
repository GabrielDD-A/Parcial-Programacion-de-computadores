from decimal import Decimal, ROUND_HALF_UP

TEMP_OPT_MIN, TEMP_OPT_MAX = 18, 26
TEMP_CRIT_MIN, TEMP_CRIT_MAX = 12, 32
HUM_OPT_MIN, HUM_OPT_MAX = 60, 80
HUM_CRIT_MIN, HUM_CRIT_MAX = 40, 90
TEMP_SENSOR_MIN, TEMP_SENSOR_MAX = -10, 60
HUM_SENSOR_MIN, HUM_SENSOR_MAX = 0, 100
MAX_LECTURAS = 8

def leer_numero(mensaje):
    """Lee un número (acepta coma o punto decimal). Devuelve None si no es numérico."""
    try:
        return float(input(mensaje).replace(",", "."))
    except ValueError:
        return None


def formato(x):
    """Muestra 29.0 como 29 y 25.5 como 25,5 (coma decimal)."""
    return str(int(x)) if x == int(x) else str(x).replace(".", ",")


def dos_decimales(x):
    """Redondea a 2 decimales (mitad hacia arriba, como Excel) y usa coma decimal."""
    d = Decimal(str(round(x, 8))).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
    return str(d).replace(".", ",")



lectura = 0
sumTemp = 0.0
sumHum = 0.0
minTemp, maxTemp = TEMP_SENSOR_MAX, TEMP_SENSOR_MIN
minHum, maxHum = HUM_SENSOR_MAX, HUM_SENSOR_MIN
secTemp = []
secHum = []
resultado = ""
terminar = False

while not terminar:

    valido = False
    while not valido:
        temp = leer_numero("Temperatura (°C): ")
        hum = leer_numero("Humedad relativa (%): ")
        valido = (temp is not None and hum is not None
                  and TEMP_SENSOR_MIN <= temp <= TEMP_SENSOR_MAX
                  and HUM_SENSOR_MIN <= hum <= HUM_SENSOR_MAX)
        if not valido:
            print("Dato inválido. Ingrese nuevamente la lectura.")

    lectura += 1
    secTemp.append(temp)
    secHum.append(hum)
    sumTemp += temp
    sumHum += hum
    if temp < minTemp:
        minTemp = temp
    if temp > maxTemp:
        maxTemp = temp
    if hum < minHum:
        minHum = hum
    if hum > maxHum:
        maxHum = hum

    if (temp < TEMP_CRIT_MIN or temp > TEMP_CRIT_MAX
            or hum < HUM_CRIT_MIN or hum > HUM_CRIT_MAX):
        estado = "Crítico"
        accion = "Alerta crítica: activar protocolo de emergencia"
        resultado = "Alerta crítica"
        terminar = True

    elif (TEMP_OPT_MIN <= temp <= TEMP_OPT_MAX
          and HUM_OPT_MIN <= hum <= HUM_OPT_MAX):
        estado = "Óptimo"
        if lectura == 1:
            accion = "Cultivo en condiciones óptimas"
            resultado = "Condiciones óptimas"
        else:
            accion = "Cultivo estabilizado"
            resultado = "Cultivo estabilizado"
        terminar = True

    else:
        estado = "Observación"
        if lectura == MAX_LECTURAS:
            accion = "Revisión técnica de los equipos"
            resultado = "Revisión técnica"
            terminar = True
        else:
            accionTemp = ""
            accionHum = ""
            if temp < TEMP_OPT_MIN:
                accionTemp = "Encender calefacción"
            elif temp > TEMP_OPT_MAX:
                accionTemp = "Ventilar"
            if hum > HUM_OPT_MAX:
                accionHum = "Deshumidificar"
            elif hum < HUM_OPT_MIN:
                accionHum = "Nebulizar"
            if accionTemp != "" and accionHum != "":
                accion = accionTemp + " y " + accionHum.lower()
            else:
                accion = accionTemp + accionHum

    print("Lectura " + str(lectura) + " | " + formato(temp) + " °C | "
          + formato(hum) + " % | " + estado + " | " + accion)


promTemp = sumTemp / lectura
promHum = sumHum / lectura

print()
print("Resultado: " + resultado + ". Lecturas tomadas: " + str(lectura) + ".")
print("Temperatura: mínima " + formato(minTemp) + " – máxima " + formato(maxTemp)
      + " – promedio " + dos_decimales(promTemp) + ".")
print("Humedad: mínima " + formato(minHum) + " – máxima " + formato(maxHum)
      + " – promedio " + dos_decimales(promHum) + ".")
print("Secuencia de temperaturas: " + "; ".join(formato(t) for t in secTemp)
      + ". Secuencia de humedades: " + "; ".join(formato(h) for h in secHum) + ".")